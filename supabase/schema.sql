-- Opcional para Push Notifications reales (KORA SIGNAL con la app cerrada).
create table if not exists public.koraverse_push_subscriptions (
  id bigint generated by default as identity primary key,
  player_key text not null,
  endpoint text not null unique,
  subscription jsonb not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
alter table public.koraverse_push_subscriptions enable row level security;
-- No se crea política anon: solo las funciones server-side con service role acceden a esta tabla.
create index if not exists idx_koraverse_push_player on public.koraverse_push_subscriptions(player_key);

