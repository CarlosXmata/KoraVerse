create table if not exists public.koraverse_profiles (
  player_key text primary key,
  display_name text not null,
  xp integer not null default 0,
  english_xp integer not null default 0,
  puzzle_xp integer not null default 0,
  arcade_xp integer not null default 0,
  duo_xp integer not null default 0,
  streak integer not null default 0,
  last_active date,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.koraverse_activity (
  id bigint generated by default as identity primary key,
  player_key text not null,
  category text not null,
  source text not null,
  xp integer not null default 0,
  created_at timestamptz not null default now()
);

create table if not exists public.koraverse_duo (
  id integer primary key default 1 check (id = 1),
  xp integer not null default 0,
  sessions integer not null default 0,
  garden_level integer not null default 1,
  updated_at timestamptz not null default now()
);
insert into public.koraverse_duo(id) values (1) on conflict (id) do nothing;

create table if not exists public.koraverse_signals (
  id bigint generated by default as identity primary key,
  from_player text not null,
  to_player text not null,
  message text not null default 'quiere jugar contigo',
  seen boolean not null default false,
  created_at timestamptz not null default now()
);

create table if not exists public.koraverse_english_progress (
  player_key text not null,
  lesson_id text not null,
  correct integer not null default 0,
  attempts integer not null default 0,
  mastery integer not null default 0,
  updated_at timestamptz not null default now(),
  primary key(player_key, lesson_id)
);

-- Contenido opcional que puedes ampliar sin volver a desplegar el front-end.
create table if not exists public.koraverse_english_content (
  id bigint generated by default as identity primary key,
  lesson_id text not null,
  level text not null,
  topic text not null,
  kind text not null,
  prompt text not null,
  options jsonb,
  answer jsonb not null,
  explanation text,
  active boolean not null default true,
  created_at timestamptz not null default now()
);

